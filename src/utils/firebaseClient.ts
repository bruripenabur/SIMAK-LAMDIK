testConnection();

// Authentication Helpers
export async function signInWithGoogle(): Promise<User> {
  try {
    const result = await signInWithPopup(auth, googleProvider);
    return result.user;
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, 'auth');
    throw error;
  }
}

export async function logoutFirebase(): Promise<void> {
  try {
    await signOut(auth);
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, 'auth');
  }
}

// Firestore Persistence Helpers for simak-lamptip
export async function saveAssessmentToFirestore(userId: string, data: any): Promise<void> {
  const path = `assessment_sessions/${userId}`;
  try {
    const docRef = doc(db, 'assessment_sessions', userId);
    const payload = {
      userId,
      updatedAt: new Date().toISOString(),
      ...data,
    };
    await setDoc(docRef, payload, { merge: true });
  } catch (error) {
    handleFirestoreError(error, OperationType.WRITE, path);
  }
}

export async function loadAssessmentFromFirestore(userId: string): Promise<any | null> {
  const path = `assessment_sessions/${userId}`;
  try {
    const docRef = doc(db, 'assessment_sessions', userId);
    const snap = await getDoc(docRef);
    if (snap.exists()) {
      return snap.data();
    }
    return null;
  } catch (error) {
    handleFirestoreError(error, OperationType.GET, path);
    return null;
  }
}
